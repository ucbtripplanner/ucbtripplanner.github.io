#!/usr/bin/env python3
"""Build <trip>/images.js (the photo registry) from <trip>/images.json.

Usage: python3 tools/build_images.py [trip-folder]        (default: 2026-yosemite)

images.json maps a short key → one of:
  {"file": "Some_Commons_File.jpg", "title": "Tunnel View", "pos": "center 40%"}
      A Wikimedia Commons file. Author + license are fetched from the Commons API and the
      thumbnail URLs (960px "src", 1280px "big") are filled in. Prefer this — it's properly licensed.
  {"src": "https://…", "credit": "공식 사이트 이미지", "license": "링크 미리보기", "page": "https://…", "title": "…"}
      An external image used as a link preview (e.g. a lodge's og:image). Kept as-is.
      Wrap heavy images with the resize proxy:  https://wsrv.nl/?url=<host/path>&w=960&output=jpg&q=78

data.js items reference keys:  img: 'tunnel-view',  pages.*.cover: 'half-dome'.
Find Commons files with:  python3 tools/find_photo.py "Grizzly Giant Mariposa Grove"
Stdlib only. Needs network.
"""
import html
import json
import os
import re
import sys
import urllib.parse
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
UA = {"User-Agent": "ucbtripplanner-site/1.0 (https://ucbtripplanner.github.io)"}


def strip(s):
    return re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", "", s or ""))).strip()


def commons(names, width):
    out = {}
    for i in range(0, len(names), 40):
        chunk = names[i:i + 40]
        url = "https://commons.wikimedia.org/w/api.php?" + urllib.parse.urlencode({
            "action": "query", "format": "json", "prop": "imageinfo", "iiprop": "url|extmetadata",
            "iiurlwidth": width, "titles": "|".join("File:" + n for n in chunk)})
        d = json.load(urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60))
        norm = {n["to"]: n["from"] for n in d["query"].get("normalized", [])}
        for p in d["query"]["pages"].values():
            name = norm.get(p["title"], p["title"]).replace("File:", "")
            out[name] = p
    return out


def main():
    trip = sys.argv[1] if len(sys.argv) > 1 else "2026-yosemite"
    spec_path = os.path.join(ROOT, trip, "images.json")
    spec = json.load(open(spec_path, encoding="utf-8"))
    names = sorted({v["file"] for v in spec.values() if "file" in v})
    small, big = commons(names, 960), commons(names, 1280)
    clean = lambda u: u.split("?")[0].replace("https://thumb.wikimedia.org/", "https://upload.wikimedia.org/")
    out, missing = {}, []
    for key, v in spec.items():
        if "file" not in v:
            out[key] = v
            continue
        p = small.get(v["file"]) or small.get(v["file"].replace("_", " "))
        q = big.get(v["file"]) or big.get(v["file"].replace("_", " "))
        if not p or "imageinfo" not in p:
            missing.append(f'{key} ({v["file"]})')
            continue
        ii, em = p["imageinfo"][0], p["imageinfo"][0].get("extmetadata", {})
        out[key] = {
            "src": clean(ii["thumburl"]),
            "big": clean(q["imageinfo"][0]["thumburl"]) if q and "imageinfo" in q else clean(ii["thumburl"]),
            "credit": strip(em.get("Artist", {}).get("value", ""))[:80] or "Wikimedia Commons",
            "license": em.get("LicenseShortName", {}).get("value", ""),
            "page": ii["descriptionurl"],
            "title": v.get("title", v["file"].rsplit(".", 1)[0].replace("_", " ")),
        }
        if v.get("pos"):
            out[key]["pos"] = v["pos"]
    dst = os.path.join(ROOT, trip, "images.js")
    with open(dst, "w", encoding="utf-8") as f:
        f.write("/* GENERATED by tools/build_images.py from images.json — edit images.json, then re-run. */\n")
        f.write("window.TRIP_IMAGES = " + json.dumps(out, ensure_ascii=False, indent=1) + ";\n")
    print(f"wrote {os.path.relpath(dst, ROOT)}: {len(out)} images")
    if missing:
        print("✗ not found on Commons:", ", ".join(missing))
        sys.exit(1)


if __name__ == "__main__":
    main()
