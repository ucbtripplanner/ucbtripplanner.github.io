#!/usr/bin/env node
// Generate the (thin) HTML shell for every page of a trip from data.js `pages` + `pageOrder`.
// All content is rendered client-side by /assets/trip.js; these shells only carry <head> meta
// (title, description, og:image for link previews in KakaoTalk/iMessage/Slack) and the script tags.
// Usage: node tools/gen_pages.mjs [trip-folder]   (default: 2026-yosemite)
// Re-run after changing a page title/desc/cover or adding a page.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SITE = 'https://ucbtripplanner.github.io';
const trip = process.argv[2] || '2026-yosemite';
const dir = path.join(ROOT, trip);
const ctx = { window: {} };
vm.createContext(ctx);
for (const f of ['images.js', 'data.js']) vm.runInContext(fs.readFileSync(path.join(dir, f), 'utf8'), ctx);
const T = ctx.window.TRIP;
const I = Object.assign({}, ctx.window.TRIP_IMAGES || {}, T.images || {});
const esc = (s) => String(s || '').replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
const MAP_PAGES = new Set(['home', 'course']); // pages that show the Leaflet map

for (const key of T.pageOrder) {
  const p = T.pages[key];
  const title = key === 'home' ? `${T.title}` : `${p.title} · ${T.short}`;
  const desc = (p.blurb || p.desc || '').replace(/\*\*/g, '');
  const og = (I[p.cover] && (I[p.cover].big || I[p.cover].src)) || '';
  const map = MAP_PAGES.has(key);
  const html = `<!doctype html>
<html lang="ko" data-theme="light">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${esc(title)}</title>
  <meta name="description" content="${esc(desc)}">
  <meta property="og:type" content="website">
  <meta property="og:site_name" content="UCB Trip Planner">
  <meta property="og:title" content="${esc(title)}">
  <meta property="og:description" content="${esc(desc)}">
  <meta property="og:url" content="${SITE}${T.base}${p.href}">
  <meta property="og:image" content="${esc(og)}">
  <meta name="twitter:card" content="summary_large_image">
  <!-- generated by tools/gen_pages.mjs — edit data.js, not this file -->
  <link rel="icon" href="data:image/svg+xml,<svg xmlns=%22http://www.w3.org/2000/svg%22 viewBox=%220 0 100 100%22><text y=%22.9em%22 font-size=%2290%22>${T.icon}</text></svg>">
  <meta name="theme-color" content="#ffffff">
  <script>try{if(localStorage.getItem('utp:theme')==='dark')document.documentElement.dataset.theme='dark'}catch(e){}</script>
  <link rel="preconnect" href="https://cdn.jsdelivr.net" crossorigin>
  <!-- fonts & map CSS load without blocking the first paint (slow park signal) -->
  <link rel="stylesheet" href="https://cdn.jsdelivr.net/gh/orioncactus/pretendard@v1.3.9/dist/web/static/pretendard-dynamic-subset.min.css" media="print" onload="this.media='all'">
${map ? '  <link rel="stylesheet" href="https://cdnjs.cloudflare.com/ajax/libs/leaflet/1.9.4/leaflet.css" media="print" onload="this.media=\'all\'">\n' : ''}  <link rel="stylesheet" href="/assets/style.css">
</head>
<body data-page="${key}">
  <div id="app"></div>
  <noscript><p>이 페이지는 JavaScript가 필요해요.</p></noscript>
${map ? '  <script async src="https://cdnjs.cloudflare.com/ajax/libs/leaflet/1.9.4/leaflet.js"></script>\n' : ''}  <script src="${T.base}images.js"></script>
  <script src="${T.base}geo.js"></script>
  <script src="${T.base}data.js"></script>
  <script src="/assets/trip.js"></script>
</body>
</html>
`;
  const out = path.join(dir, p.href, 'index.html');
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, html);
  console.log('wrote', path.relative(ROOT, out));
}
