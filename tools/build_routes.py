#!/usr/bin/env python3
"""Build <trip>/geo.js (driving-route lines for the map) from <trip>/routes.json.

Usage: python3 tools/build_routes.py [trip-folder]     (default: 2026-yosemite)

routes.json:
  {"home": {"name": "Berkeley", "ll": [37.8716, -122.2727]},
   "routes": {"hwy120": {"label": "Hwy 120 경유 …", "waypoints": [[lat, lng], …]}, …}}

Fetches road geometry from the public OSRM demo server and simplifies it (Douglas–Peucker) so the
file stays small. Course plans reference routes by key:  routes: ['hwy120', 'hwy140']  (go, return).
Distances/times from OSRM are rough — use NPS/Google numbers in the text, this is only for drawing.
"""
import json
import math
import os
import sys
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
UA = {"User-Agent": "ucbtripplanner-site/1.0 (https://ucbtripplanner.github.io)"}


def simplify(pts, tol):
    if len(pts) < 3:
        return pts

    def dist(p, a, b):
        (x, y), (x1, y1), (x2, y2) = p, a, b
        dx, dy = x2 - x1, y2 - y1
        if dx == dy == 0:
            return math.hypot(x - x1, y - y1)
        t = max(0, min(1, ((x - x1) * dx + (y - y1) * dy) / (dx * dx + dy * dy)))
        return math.hypot(x - x1 - t * dx, y - y1 - t * dy)

    keep = [False] * len(pts)
    keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        s, e = stack.pop()
        best, idx = 0, None
        for i in range(s + 1, e):
            d = dist(pts[i], pts[s], pts[e])
            if d > best:
                best, idx = d, i
        if idx is not None and best > tol:
            keep[idx] = True
            stack += [(s, idx), (idx, e)]
    return [p for p, k in zip(pts, keep) if k]


def main():
    trip = sys.argv[1] if len(sys.argv) > 1 else "2026-yosemite"
    src = json.load(open(os.path.join(ROOT, trip, "routes.json"), encoding="utf-8"))
    geo = {"home": src["home"], "routes": {}}
    for key, r in src["routes"].items():
        coords = ";".join(f"{lng},{lat}" for lat, lng in r["waypoints"])
        url = f"https://router.project-osrm.org/route/v1/driving/{coords}?overview=full&geometries=geojson"
        d = json.load(urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60))
        rt = d["routes"][0]
        pts = [(round(lat, 5), round(lng, 5)) for lng, lat in rt["geometry"]["coordinates"]]
        line = simplify(pts, 0.0012)
        geo["routes"][key] = {"label": r["label"], "miles": round(rt["distance"] / 1609.34), "line": [list(p) for p in line]}
        print(f"{key}: {geo['routes'][key]['miles']} mi, {len(pts)} → {len(line)} points")
    dst = os.path.join(ROOT, trip, "geo.js")
    with open(dst, "w", encoding="utf-8") as f:
        f.write("/* GENERATED by tools/build_routes.py from routes.json — approximate, for drawing only. */\n")
        f.write("window.TRIP_GEO = " + json.dumps(geo, ensure_ascii=False, separators=(",", ":")) + ";\n")
    print("wrote", os.path.relpath(dst, ROOT))


if __name__ == "__main__":
    main()
